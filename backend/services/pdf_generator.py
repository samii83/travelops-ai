
from pathlib import Path

from reportlab.lib import colors
from reportlab.lib.enums import TA_CENTER
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import inch
from reportlab.platypus import (
    SimpleDocTemplate,
    Paragraph,
    Spacer,
    Table,
    TableStyle
)


def generate_quotation_pdf(quotation, output_path=None):

    if output_path is None:
        output_path = (
            Path("reports") / "travel_quotation.pdf"
        )

    output_path = Path(output_path)
    output_path.parent.mkdir(parents=True, exist_ok=True)

    document = SimpleDocTemplate(
        str(output_path),
        pagesize=A4,
        rightMargin=40,
        leftMargin=40,
        topMargin=40,
        bottomMargin=40
    )

    styles = getSampleStyleSheet()

    title_style = ParagraphStyle(
        "CustomTitle",
        parent=styles["Title"],
        alignment=TA_CENTER,
        fontSize=22,
        spaceAfter=12
    )

    story = []

    story.append(Paragraph("TRAVELOPS AI", title_style))
    story.append(
        Paragraph("Travel Quotation & Cost Estimate", styles["Heading2"])
    )

    story.append(Spacer(1, 15))

    details = [
        ["Destination", quotation.destination],
        ["Duration", f"{quotation.duration_days} days"],
        ["Travelers", str(quotation.travelers)],
        ["Hotel", quotation.hotel_name],
        ["Currency", quotation.currency]
    ]

    details_table = Table(details, colWidths=[140, 350])

    details_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (0, -1), colors.whitesmoke),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.lightgrey),
        ("PADDING", (0, 0), (-1, -1), 8),
    ]))

    story.append(details_table)
    story.append(Spacer(1, 20))

    story.append(Paragraph("Cost Breakdown", styles["Heading2"]))

    rows = [["Category", "Description", "Estimated Cost (INR)"]]

    for item in quotation.items:
        rows.append([
            item.category,
            item.description,
            f"{item.amount:,.2f}"
        ])

    rows.append([
        "TOTAL",
        "Total estimated trip cost",
        f"{quotation.total_estimated_cost:,.2f}"
    ])

    cost_table = Table(
        rows,
        colWidths=[115, 245, 130],
        repeatRows=1
    )

    cost_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#17365D")),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.lightgrey),
        ("PADDING", (0, 0), (-1, -1), 7),
        ("BACKGROUND", (0, -1), (-1, -1), colors.HexColor("#DCE6F1")),
        ("FONTNAME", (0, -1), (-1, -1), "Helvetica-Bold"),
    ]))

    story.append(cost_table)
    story.append(Spacer(1, 15))

    story.append(Paragraph("Budget Summary", styles["Heading2"]))

    story.append(Paragraph(
        f"Total cost: INR {quotation.total_estimated_cost:,.2f}",
        styles["Normal"]
    ))

    story.append(Paragraph(
        f"Cost per traveler: INR {quotation.cost_per_person:,.2f}",
        styles["Normal"]
    ))

    if quotation.budget is not None:
        story.append(Paragraph(
            f"Customer budget: INR {quotation.budget:,.2f}",
            styles["Normal"]
        ))

        story.append(Paragraph(
            f"Remaining budget: INR {quotation.remaining_budget:,.2f}",
            styles["Normal"]
        ))

    story.append(Spacer(1, 15))

    story.append(Paragraph("Suggested Attractions", styles["Heading2"]))

    for attraction in quotation.attractions:
        story.append(Paragraph(
            f"- {attraction}",
            styles["Normal"]
        ))

    story.append(Spacer(1, 15))

    story.append(Paragraph("Assumptions & Disclaimer", styles["Heading2"]))

    for assumption in quotation.assumptions:
        story.append(Paragraph(
            f"- {assumption}",
            styles["Normal"]
        ))

    story.append(Spacer(1, 20))

    story.append(Paragraph(
        "Generated by TravelOps AI. This is an illustrative "
        "quotation and not a confirmed booking.",
        styles["Italic"]
    ))

    document.build(story)

    return str(output_path)
